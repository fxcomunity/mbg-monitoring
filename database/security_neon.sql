-- Required migration before deploying Cloudflare Pages server inspection.
-- Safe to rerun. Existing basic + geo columns are preserved.
-- New Pages events store NULL user_agent/payload_sample, never request content.
-- input_field identifies server:<location> versus client:<advisory type>.
-- Existing historical payloads are NOT scrubbed by this migration; review retention.

CREATE TABLE IF NOT EXISTS exploit_logs (
  id             BIGSERIAL PRIMARY KEY,
  ip_address     VARCHAR(45),
  user_agent     VARCHAR(500),
  exploit_type   VARCHAR(60) NOT NULL,
  input_field    VARCHAR(80),
  payload_sample TEXT,
  requested_url  VARCHAR(500),
  created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE exploit_logs
  ADD COLUMN IF NOT EXISTS country VARCHAR(2),
  ADD COLUMN IF NOT EXISTS region VARCHAR(100),
  ADD COLUMN IF NOT EXISTS city VARCHAR(100);

CREATE INDEX IF NOT EXISTS idx_exploit_ip_created
  ON exploit_logs (ip_address, created_at DESC);

-- Legacy compatibility only: Pages no longer increments counters or auto-bans.
CREATE TABLE IF NOT EXISTS security_threat_counters (
  ip_address        VARCHAR(45) PRIMARY KEY,
  window_started_at TIMESTAMPTZ NOT NULL,
  threat_count      INTEGER NOT NULL CHECK (threat_count > 0)
);

-- Manually managed bans. Pages consults these for APIs, WS and unsafe methods,
-- using a per-isolate 60-second cache; normal static GET/HEAD requests skip this.
CREATE TABLE IF NOT EXISTS security_blocked_ips (
  ip_address VARCHAR(45) PRIMARY KEY,
  reason     VARCHAR(200) NOT NULL,
  blocked_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  expires_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_security_blocked_expiry
  ON security_blocked_ips (expires_at);

-- Remove only bans generated by the old client-report threshold. Manual bans stay.
DELETE FROM security_blocked_ips
WHERE reason = 'Auto-block: 3 or more threats in 1 hour';

CREATE INDEX IF NOT EXISTS idx_exploit_created
  ON exploit_logs (created_at DESC);

-- Login failures are consecutive per trusted client IP; successful login resets
-- the counter. Passwords, usernames, request bodies, and raw URLs are not stored.
CREATE TABLE IF NOT EXISTS auth_ip_lockouts (
  ip_address      VARCHAR(45) PRIMARY KEY,
  failed_attempts INTEGER NOT NULL DEFAULT 0 CHECK (failed_attempts >= 0),
  locked_until    TIMESTAMPTZ,
  is_permanent    BOOLEAN NOT NULL DEFAULT FALSE,
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS auth_security_events (
  id              BIGSERIAL PRIMARY KEY,
  ip_address      VARCHAR(45) NOT NULL,
  event_type      VARCHAR(40) NOT NULL,
  failed_attempts INTEGER NOT NULL DEFAULT 0,
  blocked_until   TIMESTAMPTZ,
  is_permanent    BOOLEAN NOT NULL DEFAULT FALSE,
  actor_username  VARCHAR(80),
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE auth_security_events
  ADD COLUMN IF NOT EXISTS actor_username VARCHAR(80);

CREATE INDEX IF NOT EXISTS idx_auth_security_events_created
  ON auth_security_events (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_auth_security_events_ip_created
  ON auth_security_events (ip_address, created_at DESC);

ALTER TABLE users
  ADD COLUMN IF NOT EXISTS session_version INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS salt VARCHAR(128);
